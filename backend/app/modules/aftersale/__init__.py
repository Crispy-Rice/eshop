"""售后模块：退款、退货与逆向状态机。

对应 docs/08-aftersale.md。**本期只做核心闭环**：仅退款与退货退款两种类型，
把「用户申请 → 商家审核 → 退货/质检 → 退款到账」这条链跑通。

核心约定：

- **售后单有自己的状态机**（`state_machine.py`，表驱动 + 行锁 + CAS），
  与子单状态机**在同一事务内**联动 —— 不存在"一边改了另一边没改"的窗口。
- **库存回补的唯一节点是「入库质检合格」**（未发货的仅退款除外）。在申请或同意时
  回补会造成"用户不寄回 → 库存虚增 → 超卖"（docs/08 §3.3 点名了这个陷阱）。
- **金额在申请时冻结**（差额法定稿），退款成功时只累加、不回算 ——
  回算会在并发/重放下产生"审批金额 ≠ 打款金额"。
- **资金退款单独一个事务**：调渠道是网络请求，不能放进 DB 事务持锁。
  即时性靠 ``after_commit`` 投递，可靠性靠 ``payment_refund`` 行本身作持久队列。

不在本期：积分返还、平台仲裁、换货/补寄、防退货欺诈。
"""
